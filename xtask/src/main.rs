//! Maintainer tasks. Run with `cargo xtask <task>`.
//!
//! - `proto`: regenerate `crates/centrifuge-core/src/proto/generated.rs` from
//!   `crates/centrifuge-core/proto/client.proto`. Needs `protoc` on `PATH`.
//!   The output is committed, so users never need `protoc`.
//! - `tla-traces`: generate the TLA+ traces the core replays (see `tla.rs`).
//! - `tla-check [config...]`: model-check the replayed schedules exhaustively.

#![allow(clippy::print_stdout, clippy::print_stderr)] // a CLI

mod tla;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    let task = std::env::args().nth(1);
    let res = match task.as_deref() {
        Some("proto") => proto(),
        Some("tla-traces") => tla::traces(&workspace_root()),
        Some("tla-check") => tla::check(&workspace_root(), &std::env::args().skip(2).collect::<Vec<_>>()),
        _ => {
            eprintln!("usage: cargo xtask <proto|tla-traces|tla-check [config...]>");
            return ExitCode::FAILURE;
        }
    };
    match res {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("xtask {}: {e}", task.unwrap_or_default());
            ExitCode::FAILURE
        }
    }
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace root")
        .to_path_buf()
}

fn proto() -> Result<(), Box<dyn std::error::Error>> {
    let root = workspace_root();
    let core = root.join("crates/centrifuge-core");
    let out = std::env::temp_dir().join("centrifuge-xtask-proto");
    std::fs::create_dir_all(&out)?;
    prost_build::Config::new()
        // `bytes` fields decode as `bytes::Bytes`: slices of the frame buffer,
        // no copy (docs/spec.md §4.6).
        .bytes(["."])
        .out_dir(&out)
        .compile_protos(&[core.join("proto/client.proto")], &[core.join("proto")])?;
    let generated = std::fs::read_to_string(out.join("centrifugal.centrifuge.protocol.rs"))?;
    let header = "// @generated by `cargo xtask proto` from proto/client.proto. Do not edit.\n\n";
    std::fs::write(
        core.join("src/proto/generated.rs"),
        format!("{header}{generated}"),
    )?;
    println!("wrote crates/centrifuge-core/src/proto/generated.rs");
    Ok(())
}
